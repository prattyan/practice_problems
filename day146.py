"""
Day 146: Longest Increasing Subsequence

Question:
Find the length of the longest increasing subsequence.
"""

# Solution
def lis(a):
    dp = [1] * len(a)
    for i in range(len(a)):
        for j in range(i):
            if a[j] < a[i]:
                dp[i] = max(dp[i], dp[j] + 1)
    return max(dp)

print(lis([10, 9, 2, 5, 3, 7, 101, 18]))
